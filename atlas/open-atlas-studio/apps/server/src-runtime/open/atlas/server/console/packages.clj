(ns open.atlas.server.console.packages
  "The local package directory (doc 104 §8.17.7 E).

   A downloaded Server ships `bundles/` beside the jar: a few `.zip` graph
   packages plus an `index.edn` generated from their manifests. This namespace
   is the console's read of that directory — list what is there with each
   entry's install plan attached, and install one by name.

   Two things it deliberately does NOT do:

   - **It does not trust `index.edn` for anything an install turns on.** The
     index is a catalogue: a name, a one-line summary, a filename. Every fact
     that decides whether a package may be installed — its coordinate, its
     requirements, its compat — is read back out of the zip's own sealed
     manifest by `ops/plan-import`. An index that has drifted from the zips
     beside it can then only mislabel a row, never authorise an install.
   - **It does not resolve a caller-supplied path.** `:file` is matched against
     the directory's own listing, so `../../etc/passwd` is not a path this
     namespace normalises and rejects — it is simply not one of the files it
     found (see `entry-for`)."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.string :as str]
            [open.atlas.server.console.example :as example]
            [open.atlas.server.console.ops :as ops])
  (:import [java.io File]))

(def ^:private index-file "index.edn")

(defn- jar-directory
  "The directory the jar carrying this namespace sits in, or nil for a source
   run (where the same lookup finds a directory on the classpath).

   Located through this namespace's own resource rather than through
   `user.dir`: the packaged layout is `lib/open-atlas-server.jar` + `bundles/`,
   and the caller of a launcher is free to `cd /` first."
  ^File []
  (try
    (when-let [url (some io/resource ["open/atlas/server/console/packages__init.class"
                                      "open/atlas/server/console/packages.clj"])]
      (let [s (str url)]
        (when (str/starts-with? s "jar:file:")
          (let [jar-path (subs s (count "jar:file:") (str/index-of s "!/"))
                jar (File. (java.net.URLDecoder/decode jar-path "UTF-8"))]
            (when (.isFile jar) (.getParentFile jar))))))
    (catch Throwable _ nil)))

(defn bundles-dir
  "Where the packages live.

   In order: `OPEN_ATLAS_BUNDLES_DIR`; `OPEN_ATLAS_PACKAGE_ROOT`/bundles (the
   packaged launchers export the unpacked root); `bundles/` beside the jar's
   parent, which is the layout `scripts/package-release.sh` stages
   (`lib/open-atlas-server.jar` + `bundles/`); and only then the working
   directory, where a source run meets the repository's own `fixtures/bundles`
   — a developer running from a checkout should meet the same directory a
   downloader does, for the same reason `example.clj` falls back to the fixture.

   The jar-relative step is why the cwd candidates are LAST (install.md §7; 0.2
   acceptance defect 4): every candidate used to be relative to the process
   working directory, so a Server started from anywhere but the unpacked
   directory reported some other `bundles/` — or the repository's fixtures —
   and the packages that shipped with it were invisible."
  (^File [] (bundles-dir (System/getenv)))
  (^File [environment]
   (let [dir? (fn [^File f] (and f (.isDirectory ^File f)))
         get* #(not-empty (str (get environment % "")))]
     (or (some-> (get* "OPEN_ATLAS_BUNDLES_DIR") File.)
         (first (filter dir?
                        (concat
                         (when-let [root (get* "OPEN_ATLAS_PACKAGE_ROOT")]
                           [(io/file root "bundles")])
                         (when-let [^File jar-dir (jar-directory)]
                           [(io/file jar-dir "bundles")
                            (io/file (.getParentFile jar-dir) "bundles")])
                         [(io/file "bundles")
                          (io/file ".." "bundles")
                          (io/file "../../fixtures/bundles")
                          (io/file "fixtures/bundles")])))
         (io/file "bundles")))))

(defn read-index
  "`index.edn` → a vector of entries, or `[]` when the directory or the index
   is absent. A directory with zips and no index lists nothing: the index is
   generated by `scripts/build-bundle-index.sh` and a hand-assembled reading of
   the directory here would be a second, undeclared catalogue."
  [^File dir]
  (let [f (File. dir index-file)]
    (if-not (.isFile f)
      []
      (let [parsed (try (edn/read-string (slurp f)) (catch Throwable _ nil))]
        (if (vector? parsed) (filterv map? parsed) [])))))

(defn- bundle-base64 [^File f]
  (let [bytes (byte-array (.length f))]
    (with-open [in (io/input-stream f)]
      (.readFully (java.io.DataInputStream. in) bytes))
    (.encodeToString (java.util.Base64/getEncoder) bytes)))

(defn entry-for
  "The index entry whose `:file` is `file`, or nil.

   The comparison is against the index's own strings and the answer is a File
   built from the directory plus that entry's name, so nothing a caller writes
   reaches the filesystem as a path. A `:file` carrying a separator cannot
   match, because the generator writes basenames."
  [^File dir file]
  (when (string? file)
    (first (filter #(= file (:file %)) (read-index dir)))))

(defn list-packages
  "Every index entry with its install plan merged in (doc 104 §8.17.7 E).

   The plan's `:package`, `:graph-id` and `:version` OVERRIDE the index's:
   both come from the same zip, but the plan read them out of the sealed
   manifest just now and the index was written by a script at some earlier
   time. The index keeps what only it has — the file name and the summary.

   `installed-version` is what this instance is serving for that graph today,
   or nil. It is looked up rather than inferred: an operator asking whether
   they already have this is asking about the shelf, not about the catalogue.

   A row whose zip is missing or unreadable carries the plan's findings and
   `:would-import? false` like any other refusal — the console needs no second
   vocabulary for a row that cannot be installed."
  ([dir serving-version] (list-packages dir serving-version {}))
  ([^File dir serving-version context]
  {:status :ok
   :bundles-dir (.getPath dir)
   :packages
   (vec (for [entry (read-index dir)
              :let [f (File. dir ^String (str (:file entry)))
                    plan (if (.isFile f)
                           (ops/plan-import {:bundle (bundle-base64 f)} context)
                           {:would-import? false
                            :findings [{:code :package/absent :severity :error
                                        :path [:bundles (:file entry)]
                                        :message (str "the index lists " (:file entry)
                                                      " but it is not in " (.getPath dir))}]})
                    graph-id (or (:graph-id plan) (:graph-id entry))]]
          (merge entry
                 (select-keys plan [:package :graph-id :version :compat :requires
                                    :would-import? :findings])
                 {:graph-id graph-id
                  :installed-version (when graph-id (serving-version graph-id))})))}))

(defn install!
  "Install one package from the directory.

   The DVD package goes through `example.clj` and everything else through the
   ordinary import — and the difference is invisible from outside, which is the
   point (doc 104 §8.17.7 E). The example's model names a SQLite file that has
   to exist before the first query, so that path materialises this instance's
   copy and seals the model against it; the resulting artifact is then imported
   by the same four signed commands. One button, two paths, one audit trail."
  [{:keys [runtime] :as context} actor ^File dir {:keys [file activate?] :or {activate? true} :as input} now]
  (if-let [entry (entry-for dir file)]
    (let [f (File. dir ^String (:file entry))]
      (cond
        (not (.isFile f))
        (ops/finding-error [{:code :package/absent :severity :error
                             :path [:bundles file]
                             :message (str "the index lists " file
                                           " but it is not in " (.getPath dir))}])

        (= example/graph-id (:graph-id entry))
        (let [{:keys [files findings]} (example/artifact-files (:instance runtime) now)]
          (if (seq findings)
            (ops/finding-error findings)
            (ops/import-graph context actor (cond-> {:files files :activate? activate?} (:group-id input) (assoc :group-id (:group-id input))))))

        :else
        (ops/import-graph context actor (cond-> {:bundle (bundle-base64 f) :activate? activate?} (:group-id input) (assoc :group-id (:group-id input))))))
    (ops/finding-error [{:code :package/unknown :severity :error :path [:bundles]
                         :message (str "no package named " (pr-str file)
                                       " is listed in this instance's bundle directory")}])))
